CREATE TABLE IF NOT EXISTS posts (
  post_id INT AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  content TEXT NOT NULL,
  writer VARCHAR(100),
  date VARCHAR(50) NOT NULL,
  users_id INT,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

